create table if not exists public.payment_orders (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null references public.shop_products(id),
  product_type text not null check (product_type in ('subscription', 'credits')),
  amount integer not null check (amount > 0),
  credits integer not null default 0 check (credits >= 0),
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed')),
  toss_payment_key text unique,
  toss_payment_data jsonb,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
create index if not exists payment_orders_user_created_idx on public.payment_orders(user_id, created_at desc);
create index if not exists payment_orders_pending_idx on public.payment_orders(status, created_at) where status = 'pending';

create table if not exists public.credit_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.credit_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_id text not null unique references public.payment_orders(id),
  amount bigint not null check (amount > 0),
  description text not null,
  created_at timestamptz not null default now()
);
create index if not exists credit_transactions_user_created_idx on public.credit_transactions(user_id, created_at desc);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  product_id text not null references public.shop_products(id),
  customer_key text not null unique,
  billing_key text not null,
  status text not null default 'active' check (status in ('active', 'cancelled', 'past_due')),
  current_period_start timestamptz not null default now(),
  current_period_end timestamptz not null default (now() + interval '1 month'),
  cancel_at_period_end boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

