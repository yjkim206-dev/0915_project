  end loop;
end $$;

create or replace function public.guard_subscription_checkout_close()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if old.product_type='subscription' and old.status='pending' and new.status in ('cancelled','failed')
    and exists(select 1 from public.subscription_payment_attempts where order_id=old.id) then
    raise exception 'PAYMENT_IN_PROGRESS';
  end if;
  return new;
end;
$$;
create trigger guard_subscription_checkout_close before update of status on public.payment_orders
  for each row execute function public.guard_subscription_checkout_close();
revoke all on function public.guard_subscription_checkout_close() from public,anon,authenticated;
