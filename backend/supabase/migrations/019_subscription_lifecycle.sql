alter table public.subscriptions
  alter column billing_key drop not null,
  add column if not exists billing_mode text not null default 'automatic' check (billing_mode in ('manual', 'automatic')),
  add column if not exists last_order_id text references public.payment_orders(id) on delete set null,
  add column if not exists last_error text,
  add column if not exists canceled_at timestamptz;
alter table public.payment_orders
  add column if not exists subscription_mode text check (subscription_mode in ('manual', 'automatic')),
  add column if not exists subscription_id bigint references public.subscriptions(id) on delete set null,
  add column if not exists subscription_period_start timestamptz,
  add column if not exists subscription_period_end timestamptz;
update public.payment_orders set subscription_mode = 'automatic' where product_type = 'subscription' and subscription_mode is null;
update public.subscriptions s set last_order_id = (
  select id from public.payment_orders o where o.user_id = s.user_id and o.product_type = 'subscription' and o.status = 'paid' order by paid_at desc nulls last limit 1
) where last_order_id is null;
update public.payment_orders o set subscription_id = s.id,
  subscription_period_start = s.current_period_start, subscription_period_end = s.current_period_end
from public.subscriptions s where o.id = s.last_order_id;

create table public.subscription_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  subscription_id bigint references public.subscriptions(id) on delete set null,
  order_id text references public.payment_orders(id) on delete set null,
  event_type text not null, description text not null,
  created_at timestamptz not null default now()
);
create index subscription_events_user_created_idx on public.subscription_events(user_id, created_at desc);
alter table public.subscription_events enable row level security;
create policy "users read own subscription events" on public.subscription_events for select to authenticated using (auth.uid() = user_id);

-- Billing keys never leave the server, including through the direct Data API.
revoke select on public.subscriptions from anon, authenticated;
grant select (id,user_id,product_id,status,current_period_start,current_period_end,cancel_at_period_end,
  billing_mode,last_order_id,last_error,canceled_at,created_at,updated_at) on public.subscriptions to authenticated;
create table public.subscription_payment_attempts (
  order_id text primary key references public.payment_orders(id) on delete cascade,
  billing_key text,
  lease_until timestamptz not null default now(),
  request_id uuid not null default gen_random_uuid()
);
alter table public.subscription_payment_attempts enable row level security;
revoke all on public.subscription_payment_attempts from anon, authenticated;

create or replace function public.create_subscription_purchase(p_user_id uuid, p_mode text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_order public.payment_orders%rowtype; v_sub public.subscriptions%rowtype; v_product public.shop_products%rowtype;
begin
  if p_mode is null or p_mode not in ('manual', 'automatic') then raise exception 'INVALID_MODE'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':subscription', 0));
  select * into v_sub from public.subscriptions where user_id = p_user_id for update;
  if v_sub.status = 'active' and v_sub.current_period_end > now() then raise exception 'SUBSCRIPTION_ACTIVE'; end if;
  if exists (select 1 from public.payment_orders where user_id=p_user_id and refund_reserved and product_type='subscription') then raise exception 'REFUND_IN_PROGRESS'; end if;
  select * into v_product from public.shop_products where id='premium_monthly' and is_active;
  if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
  select * into v_order from public.payment_orders where user_id=p_user_id and product_type='subscription'
    and status='pending' and subscription_mode=p_mode and created_at > now()-interval '30 minutes'
    order by created_at desc limit 1;
  if not found then
    insert into public.payment_orders(id,user_id,product_id,product_name,product_type,amount,credits,subscription_mode)
    values ('MOA_'||replace(gen_random_uuid()::text,'-',''),p_user_id,v_product.id,v_product.name,'subscription',v_product.amount,0,p_mode) returning * into v_order;
  end if;
  return jsonb_build_object('orderId',v_order.id,'orderName',v_order.product_name,'amount',v_order.amount,'mode',p_mode,'customerKey','moa_'||replace(p_user_id::text,'-',''));
end;
$$;

create or replace function public.claim_subscription_payment(p_order_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_order public.payment_orders%rowtype; v_sub public.subscriptions%rowtype; v_attempt public.subscription_payment_attempts%rowtype;
begin
  select * into v_order from public.payment_orders where id=p_order_id;
  if not found or v_order.product_type <> 'subscription' then raise exception 'ORDER_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_order.user_id::text||':subscription',0));
  select * into v_order from public.payment_orders where id=p_order_id for update;
  if v_order.status='paid' then return jsonb_build_object('alreadyProcessed',true); end if;
  if v_order.status <> 'pending' then raise exception 'ORDER_NOT_PENDING'; end if;
  select * into v_sub from public.subscriptions where user_id=v_order.user_id for update;
  if v_sub.status='active' and v_sub.current_period_end>now() then raise exception 'SUBSCRIPTION_ACTIVE'; end if;
  if exists(select 1 from public.payment_orders o join public.subscription_payment_attempts a on a.order_id=o.id
    where o.user_id=v_order.user_id and o.id<>p_order_id and o.status='pending' and a.lease_until>now()) then raise exception 'PAYMENT_IN_PROGRESS'; end if;
  if v_order.subscription_id is not null and (v_sub.cancel_at_period_end or v_sub.status <> 'active') then raise exception 'RENEWAL_CANCELED'; end if;
  insert into public.subscription_payment_attempts(order_id,lease_until) values(p_order_id,now()) on conflict do nothing;
  select * into v_attempt from public.subscription_payment_attempts where order_id=p_order_id for update;
  if v_attempt.lease_until>now() then raise exception 'PAYMENT_IN_PROGRESS'; end if;
  update public.subscription_payment_attempts set lease_until=now()+interval '3 minutes' where order_id=p_order_id;
  return jsonb_build_object('alreadyProcessed',false,'requestId',v_attempt.request_id);
end;
$$;

create or replace function public.settle_subscription_purchase(p_order_id text,p_payment_key text,p_payment_data jsonb,p_billing_key text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_order public.payment_orders%rowtype; v_sub public.subscriptions%rowtype; v_start timestamptz; v_end timestamptz;
begin
  select * into v_order from public.payment_orders where id=p_order_id;
  if not found or v_order.product_type<>'subscription' then raise exception 'ORDER_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_order.user_id::text||':subscription',0));
  select * into v_order from public.payment_orders where id=p_order_id for update;
  if v_order.status='paid' then return jsonb_build_object('orderId',p_order_id,'alreadyProcessed',true,'currentPeriodEnd',v_order.subscription_period_end); end if;
  if v_order.status<>'pending' then raise exception 'ORDER_NOT_PENDING'; end if;
  if (p_payment_data->>'orderId') is distinct from p_order_id or (p_payment_data->>'totalAmount')::integer is distinct from v_order.amount
    or (p_payment_data->>'status') is distinct from 'DONE' then raise exception 'PAYMENT_MISMATCH'; end if;
  select * into v_sub from public.subscriptions where user_id=v_order.user_id for update;
  if v_sub.status='active' and v_sub.current_period_end>now() then raise exception 'SUBSCRIPTION_ACTIVE'; end if;
  if v_order.subscription_mode='automatic' and coalesce(p_billing_key,'')='' then raise exception 'BILLING_KEY_REQUIRED'; end if;
  v_start:=coalesce(v_order.subscription_period_start,now()); v_end:=coalesce(v_order.subscription_period_end,v_start+interval '1 month');
  insert into public.subscriptions(user_id,product_id,customer_key,billing_key,status,current_period_start,current_period_end,billing_mode,last_order_id)
    values(v_order.user_id,v_order.product_id,'moa_'||replace(v_order.user_id::text,'-',''),p_billing_key,'active',v_start,v_end,v_order.subscription_mode,p_order_id)
  on conflict(user_id) do update set product_id=excluded.product_id,billing_key=excluded.billing_key,status='active',
    current_period_start=v_start,current_period_end=v_end,billing_mode=excluded.billing_mode,last_order_id=p_order_id,
    cancel_at_period_end=false,last_error=null,canceled_at=null,updated_at=now() returning * into v_sub;
  update public.payment_orders set status='paid',toss_payment_key=p_payment_key,toss_payment_data=p_payment_data,paid_at=now(),
    subscription_id=v_sub.id,subscription_period_start=v_start,subscription_period_end=v_end where id=p_order_id;
  update public.subscription_payment_attempts set lease_until=now() where order_id=p_order_id;
  insert into public.subscription_events(user_id,subscription_id,order_id,event_type,description)
    values(v_order.user_id,v_sub.id,p_order_id,'payment_paid',case when v_order.subscription_mode='manual' then '1개월 이용권 구매 완료' else '자동갱신 구독 결제 완료' end);
  return jsonb_build_object('orderId',p_order_id,'status','active','mode',v_order.subscription_mode,'currentPeriodEnd',v_end,'alreadyProcessed',false);
end;
$$;

create or replace function public.change_subscription_renewal(p_user_id uuid,p_actor_id uuid,p_cancel boolean,p_reason text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_sub public.subscriptions%rowtype;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text||':subscription',0));
  select * into v_sub from public.subscriptions where user_id=p_user_id for update;
  if not found or v_sub.status<>'active' then raise exception 'SUBSCRIPTION_NOT_ACTIVE'; end if;
  if exists(select 1 from public.payment_orders o join public.subscription_payment_attempts a on a.order_id=o.id
    where o.user_id=p_user_id and o.status='pending') then raise exception 'PAYMENT_IN_PROGRESS'; end if;
  if exists(select 1 from public.payment_orders where user_id=p_user_id and product_type='subscription' and refund_reserved) then raise exception 'REFUND_IN_PROGRESS'; end if;
  if not p_cancel and (v_sub.billing_mode<>'automatic' or v_sub.current_period_end<=now()) then raise exception 'RESTART_NOT_ALLOWED'; end if;
  if v_sub.cancel_at_period_end is distinct from p_cancel then
    update public.subscriptions set cancel_at_period_end=p_cancel,canceled_at=case when p_cancel then now() else null end,updated_at=now() where id=v_sub.id;
    insert into public.subscription_events(user_id,actor_id,subscription_id,event_type,description)
      values(p_user_id,p_actor_id,v_sub.id,case when p_cancel then 'cancel_scheduled' else 'cancel_revoked' end,p_reason);
  end if;
  return jsonb_build_object('status','active','current_period_end',v_sub.current_period_end,'cancel_at_period_end',p_cancel);
end;
$$;

create or replace function public.prepare_subscription_refund(p_order_id text,p_actor_id uuid,p_reason text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_order public.payment_orders%rowtype; v_sub public.subscriptions%rowtype; v_request uuid:=gen_random_uuid();
begin
  select * into v_order from public.payment_orders where id=p_order_id;
  if not found or v_order.product_type<>'subscription' then raise exception 'ORDER_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_order.user_id::text||':subscription',0));
  select * into v_order from public.payment_orders where id=p_order_id for update;
  if v_order.status='refunded' then return jsonb_build_object('alreadyProcessed',true); end if;
  select * into v_sub from public.subscriptions where user_id=v_order.user_id for update;
  if v_order.status<>'paid' or v_sub.last_order_id is distinct from p_order_id then raise exception 'LATEST_PAYMENT_ONLY'; end if;
  if exists(select 1 from public.payment_orders o join public.subscription_payment_attempts a on a.order_id=o.id
    where o.user_id=v_order.user_id and o.status='pending') then raise exception 'PAYMENT_IN_PROGRESS'; end if;
  if v_order.refund_reserved then return jsonb_build_object('alreadyProcessed',false,'requestId',v_order.refund_request_id,'reason',v_order.cancel_reason); end if;
  update public.subscriptions set cancel_at_period_end=true,updated_at=now() where id=v_sub.id;
  update public.payment_orders set refund_reserved=true,refund_request_id=v_request,cancel_reason=p_reason where id=p_order_id;
  insert into public.subscription_events(user_id,actor_id,subscription_id,order_id,event_type,description)
    values(v_order.user_id,p_actor_id,v_sub.id,p_order_id,'refund_requested',p_reason);
  return jsonb_build_object('alreadyProcessed',false,'requestId',v_request,'reason',p_reason);
end;
$$;

create or replace function public.finish_subscription_refund(p_order_id text,p_actor_id uuid,p_cancel_data jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_order public.payment_orders%rowtype;
begin
  select * into v_order from public.payment_orders where id=p_order_id;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_order.user_id::text||':subscription',0));
  select * into v_order from public.payment_orders where id=p_order_id for update;
  if v_order.status='refunded' then return jsonb_build_object('orderId',p_order_id,'alreadyProcessed',true); end if;
  if v_order.product_type<>'subscription' or not v_order.refund_reserved then raise exception 'REFUND_NOT_PREPARED'; end if;
  if (p_cancel_data->>'status') is distinct from 'CANCELED' or (p_cancel_data->>'orderId') is distinct from p_order_id
    or (p_cancel_data->>'totalAmount')::integer is distinct from v_order.amount then raise exception 'PAYMENT_MISMATCH'; end if;
  update public.payment_orders set status='refunded',refund_reserved=false,canceled_at=now(),toss_cancel_data=p_cancel_data where id=p_order_id;
  update public.subscriptions set status='cancelled',cancel_at_period_end=true,canceled_at=now(),current_period_end=least(current_period_end,now()),updated_at=now()
    where user_id=v_order.user_id and last_order_id=p_order_id;
  insert into public.subscription_events(user_id,actor_id,subscription_id,order_id,event_type,description)
    values(v_order.user_id,p_actor_id,v_order.subscription_id,p_order_id,'refunded',coalesce(v_order.cancel_reason,'구독 결제 환불'));
  return jsonb_build_object('orderId',p_order_id,'status','refunded','refundedAmount',v_order.amount,'alreadyProcessed',false);
end;
$$;

create or replace function public.prepare_subscription_renewal(p_subscription_id bigint)
returns text language plpgsql security definer set search_path = public as $$
declare v_sub public.subscriptions%rowtype; v_order_id text; v_start timestamptz;
begin
  select * into v_sub from public.subscriptions where id=p_subscription_id;
  if not found then return null; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_sub.user_id::text||':subscription',0));
  select * into v_sub from public.subscriptions where id=p_subscription_id for update;
  if v_sub.status<>'active' or v_sub.cancel_at_period_end or v_sub.billing_mode<>'automatic' or v_sub.current_period_end>now() then return null; end if;
  if exists(select 1 from public.payment_orders where user_id=v_sub.user_id and product_type='subscription' and refund_reserved) then return null; end if;
  v_order_id:='MOA_RENEW_'||md5(v_sub.id::text||v_sub.last_order_id||v_sub.current_period_end::text);
  v_start:=greatest(v_sub.current_period_end,now());
  insert into public.payment_orders(id,user_id,product_id,product_name,product_type,amount,credits,subscription_mode,subscription_id,subscription_period_start,subscription_period_end)
    select v_order_id,v_sub.user_id,p.id,p.name,'subscription',p.amount,0,'automatic',v_sub.id,v_start,v_start+interval '1 month'
    from public.shop_products p where p.id=v_sub.product_id and p.is_active on conflict(id) do nothing;
  if not exists(select 1 from public.payment_orders where id=v_order_id) then raise exception 'PRODUCT_NOT_FOUND'; end if;
  return v_order_id;
end;
$$;

create or replace function public.expire_subscriptions()
returns integer language plpgsql security definer set search_path = public as $$
declare v_count integer;
begin
  with expired as (
    update public.subscriptions set status='cancelled',updated_at=now()
    where status='active' and current_period_end<=now() and (billing_mode='manual' or cancel_at_period_end)
    returning id,user_id
  ) insert into public.subscription_events(user_id,subscription_id,event_type,description)
    select user_id,id,'expired','구독 이용기간 종료' from expired;
  get diagnostics v_count=row_count; return v_count;
end;
$$;

