create table if not exists public.shop_products (
  id text primary key,
  product_type text not null check (product_type in ('subscription', 'credits')),
  name text not null,
  amount integer not null check (amount > 0),
  credits integer not null default 0 check (credits >= 0),
  billing_interval text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint shop_products_billing_type check (
    (product_type = 'subscription' and billing_interval is not null) or
    (product_type = 'credits' and billing_interval is null)
  )
);

