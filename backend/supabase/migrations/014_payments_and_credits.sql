create or replace function public.settle_credit_order(p_order_id text, p_payment_key text, p_payment_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.payment_orders%rowtype;
  v_balance bigint;
begin
  select * into v_order from public.payment_orders where id = p_order_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if v_order.product_type <> 'credits' then raise exception 'INVALID_PRODUCT_TYPE'; end if;
  if v_order.status = 'paid' then
    select balance into v_balance from public.credit_wallets where user_id = v_order.user_id;
    return jsonb_build_object('orderId', v_order.id, 'status', 'paid', 'balance', coalesce(v_balance, 0), 'credits', v_order.credits, 'alreadyProcessed', true);
  end if;
  update public.payment_orders set status = 'paid', toss_payment_key = p_payment_key, toss_payment_data = p_payment_data, paid_at = now() where id = p_order_id;
  insert into public.credit_wallets(user_id, balance) values (v_order.user_id, v_order.credits)
    on conflict (user_id) do update set balance = public.credit_wallets.balance + excluded.balance, updated_at = now();
  insert into public.credit_transactions(user_id, order_id, amount, description)
    values (v_order.user_id, v_order.id, v_order.credits, '포인트 충전');
  select balance into v_balance from public.credit_wallets where user_id = v_order.user_id;
  return jsonb_build_object('orderId', v_order.id, 'status', 'paid', 'balance', v_balance, 'credits', v_order.credits, 'alreadyProcessed', false);
end;
$$;

revoke all on function public.settle_credit_order(text, text, jsonb) from public, anon, authenticated;
grant execute on function public.settle_credit_order(text, text, jsonb) to service_role;

create or replace function public.settle_subscription_order(
  p_order_id text,
  p_customer_key text,
  p_billing_key text,
  p_payment_key text,
  p_payment_data jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.payment_orders%rowtype;
  v_start timestamptz := now();
  v_end timestamptz := now() + interval '1 month';
begin
  select * into v_order from public.payment_orders where id = p_order_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if v_order.product_type <> 'subscription' then raise exception 'INVALID_PRODUCT_TYPE'; end if;
  if v_order.status = 'paid' then
    return jsonb_build_object('orderId', v_order.id, 'status', 'active', 'alreadyProcessed', true);
  end if;
  update public.payment_orders
    set status = 'paid', toss_payment_key = p_payment_key, toss_payment_data = p_payment_data, paid_at = v_start
    where id = p_order_id;
  insert into public.subscriptions(user_id, product_id, customer_key, billing_key, status, current_period_start, current_period_end, updated_at)
    values (v_order.user_id, v_order.product_id, p_customer_key, p_billing_key, 'active', v_start, v_end, v_start)
    on conflict (user_id) do update set
      product_id = excluded.product_id,
      customer_key = excluded.customer_key,
      billing_key = excluded.billing_key,
      status = 'active',
      current_period_start = excluded.current_period_start,
      current_period_end = excluded.current_period_end,
      cancel_at_period_end = false,
      updated_at = excluded.updated_at;
  return jsonb_build_object('orderId', v_order.id, 'status', 'active', 'currentPeriodEnd', v_end);
end;
$$;

revoke all on function public.settle_subscription_order(text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.settle_subscription_order(text, text, text, text, jsonb) to service_role;

